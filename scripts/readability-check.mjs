#!/usr/bin/env node
// Readability check for a theme token file (default: src/ui/theme/chalk.json).
// Checks: WCAG contrast of every text/background pair, colour-blind separation of
// double vs treble, contrast under screen glare, and the physical size of every
// number role on real iPhone screens at its viewing distance.
// Usage: node scripts/readability-check.mjs [tokens.json] > docs/design/chalk-readability.md
import { readFileSync } from 'node:fs';

const file = process.argv[2] ?? new URL('../src/ui/theme/chalk.json', import.meta.url);
const tokens = JSON.parse(readFileSync(file, 'utf8'));

// ---------- colour maths ----------
const hexToRgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
};
const toLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const toSrgb = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const luminance = (lin) => 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
const linOf = (hex) => hexToRgb(hex).map(toLinear);
const contrast = (y1, y2) => (Math.max(y1, y2) + 0.05) / (Math.min(y1, y2) + 0.05);
const contrastHex = (a, b) => contrast(luminance(linOf(a)), luminance(linOf(b)));

// Machado, Oliveira & Fernandes (2009), severity 1.0, applied in linear RGB.
const CVD = {
  protanopia: [[0.152286, 1.052583, -0.204868], [0.114503, 0.786281, 0.099216], [-0.003882, -0.048116, 1.051998]],
  deuteranopia: [[0.367322, 0.860646, -0.227968], [0.280085, 0.672501, 0.047413], [-0.01182, 0.04294, 0.968881]],
  tritanopia: [[1.255528, -0.076749, -0.178779], [-0.078411, 0.930809, 0.147602], [0.004733, 0.691367, 0.3039]],
};
const clamp01 = (x) => Math.min(1, Math.max(0, x));
const simulate = (lin, m) => m.map((row) => clamp01(row[0] * lin[0] + row[1] * lin[1] + row[2] * lin[2]));
const linToHex = (lin) =>
  '#' + lin.map((c) => Math.round(toSrgb(c) * 255).toString(16).padStart(2, '0')).join('').toUpperCase();

// CIE76 ΔE in Lab (D65)
const toLab = (lin) => {
  const X = (0.4124 * lin[0] + 0.3576 * lin[1] + 0.1805 * lin[2]) / 0.95047;
  const Y = 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
  const Z = (0.0193 * lin[0] + 0.1192 * lin[1] + 0.9505 * lin[2]) / 1.08883;
  const f = (t) => (t > 216 / 24389 ? Math.cbrt(t) : (841 / 108) * t + 4 / 29);
  return [116 * f(Y) - 16, 500 * (f(X) - f(Y)), 200 * (f(Y) - f(Z))];
};
const deltaE = (a, b) => Math.hypot(...toLab(a).map((v, i) => v - toLab(b)[i]));

// ---------- size maths ----------
// iPhone points per millimetre: 163 pt/in (SE, 2x @ 326 ppi) and 153.3 pt/in (15/16, 3x @ 460 ppi).
const DEVICES = [
  { name: 'iPhone SE (375 pt wide)', mmPerPt: 25.4 / 163, widthPt: 375 },
  { name: 'iPhone 15/16 (393 pt wide)', mmPerPt: 25.4 / 153.3, widthPt: 393 },
];
const arcmin = (mm, distanceM) => (2 * Math.atan(mm / 2 / (distanceM * 1000)) * 180 * 60) / Math.PI;
// ISO 9241-303 / ANSI-HFES 100: character height ≥ 16′ minimum, 20–22′ preferred.
const MIN_ARCMIN = 16;
const PREF_ARCMIN = 20;
const SNELLEN_20_20 = 5; // a 20/20 letter subtends 5′

const fmt = (n, d = 1) => n.toFixed(d);
const out = [];
const p = (s = '') => out.push(s);

p(`# ${tokens.name} readability check`);
p();
p(`Generated by \`scripts/readability-check.mjs\` from \`src/ui/theme/chalk.json\`. Re-run after any token change.`);
p();

// 1. Contrast
p('## 1. Contrast (WCAG 2.x ratio)');
p();
p('Targets: **7:1** (AAA) for every score number and primary text; **4.5:1** for secondary text; **3:1** for outlines and non-text cues.');
p();
const PAIRS = [
  ['Remaining score / body text', 'text', 'bg', 7],
  ['Active player text on active card', 'activeText', 'activeBg', 7],
  ['Secondary text (stats, labels)', 'textMuted', 'bg', 4.5],
  ['Secondary text on a card', 'textMuted', 'surface', 4.5],
  ['Key labels', 'keyText', 'keyBg', 7],
  ['Treble chip text on treble fill', 'trebleInk', 'treble', 7],
  ['Double chip text (outline chip)', 'double', 'bg', 4.5],
  ['Double outline vs background', 'double', 'bg', 3],
  ['Treble fill vs background', 'treble', 'bg', 3],
  ['Active-card outline vs background', 'activeLine', 'bg', 3],
  ['Accent (countdown ring, selected toggle) vs background', 'accent', 'bg', 3],
  ['Selected-toggle text on accent', 'accentInk', 'accent', 7],
];
let fails = 0;
for (const [themeName, t] of Object.entries(tokens.themes)) {
  p(`### ${themeName === 'dark' ? 'Chalk (dark)' : 'Whiteboard (light)'}`);
  p();
  p('| Pair | Colours | Ratio | Target | Result |');
  p('|---|---|---|---|---|');
  for (const [label, fg, bg, target] of PAIRS) {
    const r = contrastHex(t[fg], t[bg]);
    const ok = r >= target;
    if (!ok) fails++;
    p(`| ${label} | \`${t[fg]}\` on \`${t[bg]}\` | ${fmt(r, 2)}:1 | ${target}:1 | ${ok ? 'pass' : '**FAIL**'} |`);
  }
  p();
}

// 2. Glare
p('## 2. Bright room: contrast under screen glare');
p();
p('Effective contrast = (Y₁·L + R) / (Y₂·L + R), with the screen at **L = 800 nits** and R = luminance reflected off the glass (≈ 5 % of ambient illuminance ÷ π). Below about 3:1, numbers start to wash out.');
p();
p('| Ambient | R (nits) | Chalk: score on bg | Whiteboard: score on bg |');
p('|---|---|---|---|');
const L = 800;
for (const [label, lux] of [['Living room, evening (150 lx)', 150], ['Office / kitchen (500 lx)', 500], ['Bright room by a window (2 000 lx)', 2000], ['Direct sun through glass (10 000 lx)', 10000]]) {
  const R = (lux * 0.05) / Math.PI;
  const eff = (t) => {
    const y1 = luminance(linOf(t.text)), y2 = luminance(linOf(t.bg));
    return (Math.max(y1, y2) * L + R) / (Math.min(y1, y2) * L + R);
  };
  p(`| ${label} | ${fmt(R, 0)} | ${fmt(eff(tokens.themes.dark), 1)}:1 | ${fmt(eff(tokens.themes.light), 1)}:1 |`);
}
p();
p('The ratios are similar, but dark-on-light (positive polarity) reads better in bright surroundings: the pupil narrows and bright text on dark halates, especially with astigmatism. **Whiteboard is the bright-room theme.** Safari exposes no ambient-light sensor, so the app follows the system appearance and adds a one-tap *Bright room* switch in the in-game menu.');
p();

// 3. Colour-blind separation
p('## 3. Double vs treble for colour-blind players');
p();
p('Simulated with Machado et al. (2009) at full severity. ΔE (CIE76) below ~10 means the hues are hard to tell apart; luminance contrast below 1.5:1 means they are similar in brightness too. Chips never rely on colour alone: **T = solid fill + "T" prefix**, **D = double-line outline + "D" prefix**, single = plain number.');
p();
p('| Theme | Vision | Treble | Double | ΔE | Luminance contrast |');
p('|---|---|---|---|---|---|');
for (const [themeName, t] of Object.entries(tokens.themes)) {
  const T = linOf(t.treble), D = linOf(t.double);
  const rows = [['Typical', T, D], ...Object.entries(CVD).map(([n, m]) => [n[0].toUpperCase() + n.slice(1), simulate(T, m), simulate(D, m)])];
  for (const [vision, a, b] of rows) {
    p(`| ${themeName === 'dark' ? 'Chalk' : 'Whiteboard'} | ${vision} | \`${linToHex(a)}\` | \`${linToHex(b)}\` | ${fmt(deltaE(a, b), 0)} | ${fmt(contrast(luminance(a), luminance(b)), 2)}:1 |`);
  }
}
p();

// 4. Physical size
p('## 4. Size from the oche (2.4 m) and in the hand (0.5 m)');
p();
p(`Digit height = font size × digit-height ratio, measured in the browser (Barlow Condensed 800: ${tokens.fonts.numbers.digitHeightEm} em; Atkinson Hyperlegible 700: ${tokens.fonts.ui.digitHeightEm} em). Angle = visual angle at the role's viewing distance. **Targets: ≥ ${MIN_ARCMIN}′ minimum, ≥ ${PREF_ARCMIN}′ preferred** (ISO 9241-303 / ANSI-HFES 100 for character height). For reference, a 20/20 letter is ${SNELLEN_20_20}′.`);
p();
p('Each role states the distance it is read from: **2.4 m** (the oche) or **0.35 m** (phone in hand). Roles marked *secondary* have a lower floor of 10′ (2× a 20/20 letter) because a larger number carries the same information, e.g. the turn total above the chips. The *at 2.4 m* column shows every role from the oche, for reference.');
p();
const CHIP_PAD_PT = 8; // horizontal padding each side of a chip
const CHIP_GAP_PT = 6;
const fitCell = (role, spec, f, d) => {
  if (spec.chipRow) {
    const avail = d.widthPt - 32;
    const row = (w) => 3 * (w * spec.size + 2 * CHIP_PAD_PT) + 2 * CHIP_GAP_PT;
    const t20 = row(f.chipWidthEm.T20), bull = row(f.chipWidthEm.BULL);
    if (t20 > avail) fails++;
    return `T20×3: ${t20 <= avail ? 'yes' : '**no**'} (${fmt(t20, 0)}/${fmt(avail, 0)}); BULL×3: ${bull <= avail ? 'yes' : 'scales to fit'}`;
  }
  if (!/remaining|turnTotal/.test(role)) return '–';
  const avail = role === 'remaining2up' ? (d.widthPt - 32 - 8) / 2 - 20 : d.widthPt - 32 - 24;
  const need = spec.size * f.digit3WidthEm;
  if (need > avail) fails++;
  return `"180": ${need <= avail ? 'yes' : '**no**'} (${fmt(need, 0)}/${fmt(avail, 0)})`;
};
for (const d of DEVICES) {
  p(`### ${d.name}`);
  p();
  p('| View | Role | Font (pt) | Digit height | Read from | Angle | Target | Result | at 2.4 m | Fits width (pt) |');
  p('|---|---|---|---|---|---|---|---|---|---|');
  for (const [view, roles] of Object.entries(tokens.typeScalePt)) {
    for (const [role, spec] of Object.entries(roles)) {
      const f = tokens.fonts[spec.font];
      const mm = spec.size * f.digitHeightEm * d.mmPerPt;
      const a = arcmin(mm, spec.distanceM);
      const floor = spec.minArcmin ?? MIN_ARCMIN;
      const res = a >= PREF_ARCMIN ? 'preferred' : a >= floor ? (spec.minArcmin ? 'secondary' : 'minimum') : '**below**';
      if (a < floor) fails++;
      const label = spec.note ? `${role} (${spec.note})` : role;
      p(`| ${view} | ${label} | ${spec.size} | ${fmt(mm)} mm | ${spec.distanceM} m | ${fmt(a, 0)}′ | ≥${floor}′ | ${res} | ${fmt(arcmin(mm, 2.4), 0)}′ | ${fitCell(role, spec, f, d)} |`);
    }
  }
  p();
}

p('## Result');
p();
p(fails === 0 ? '**All checks pass.**' : `**${fails} check(s) below target.** See the rows marked FAIL / below.`);
console.log(out.join('\n'));
process.exitCode = fails === 0 ? 0 : 1;
